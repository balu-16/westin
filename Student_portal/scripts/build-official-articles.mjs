/**
 * Generates src/public/officialArticles.ts from the completed crawl.
 *
 *   node scripts/build-official-articles.mjs
 *
 * Every article body is reproduced verbatim from
 * references/official-crawl.local/json/post__*.json, so the published copy is
 * the college's own. The bodies live in their own module and are imported
 * lazily by /blog/<slug>, keeping them out of the Home bundle.
 */
import { readFile, readdir, writeFile } from 'node:fs/promises'
import { join, resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const app = resolve(here, '..')
const jsonDir = resolve(app, '../references/official-crawl.local/json')

const BODY_TYPES = new Set(['p', 'h1', 'h2', 'h3', 'h4', 'h5', 'h6', 'li', 'blockquote'])

/** Reader furniture and bylines that are not article content. */
const NOISE = [
  /^Writer: Westin College$/i,
  /^Westin College$/,
  /^\d+\s*min read$/i,
  /^[A-Z][a-z]{2}\s+\d{1,2}$/,
  /^\[?\d+\]?$/,
]

const clean = (text) => (text || '').replace(/ /g, ' ').replace(/[ \t]+/g, ' ').trim()

const files = (await readdir(jsonDir)).filter((f) => f.startsWith('post__') && f.endsWith('.json')).sort()
const articles = []

for (const file of files) {
  const slug = file.replace(/\.json$/, '')
  const page = JSON.parse(await readFile(join(jsonDir, file), 'utf8'))
  const blocks = page?.sections?.main ?? []
  const body = []
  for (const block of blocks) {
    if (!BODY_TYPES.has(block.t)) continue
    const text = clean(block.text)
    if (!text) continue
    if (text.length < 3) continue
    if (NOISE.some((pattern) => pattern.test(text))) continue
    // Wix repeats the article title inside the body; keep it only as the H1.
    if (block.t === 'h1') continue
    if (/^by\s+westin college$/i.test(text)) continue
    body.push({ t: block.t, text })
  }
  if (!body.length) {
    console.warn(`  ! ${slug}: no body blocks extracted`)
    continue
  }
  const words = body.map((b) => b.text).join(' ').split(/\s+/).length
  articles.push({
    slug,
    title: page.title || slug,
    description: page.description || '',
    body,
    words,
  })
}

const quote = (value) => JSON.stringify(value)
const lines = []
lines.push('/**')
lines.push(' * Full article bodies from the official Westin journal, reproduced verbatim')
lines.push(' * from references/official-crawl.local/json/post__*.json.')
lines.push(' *')
lines.push(' * GENERATED by scripts/build-official-articles.mjs — do not edit by hand.')
lines.push(' * This module is imported lazily by /blog/<slug> so the 28k words stay out of')
lines.push(' * the Home bundle. Some articles name competitor colleges; that is the')
lines.push(' * college’s own published content and is preserved unchanged.')
lines.push(' */')
lines.push('')
lines.push('export interface ArticleBlock {')
lines.push('  /** Source tag: "p" for a paragraph, "h2".."h6" for headings, "li" for list items. */')
lines.push('  t: string')
lines.push('  text: string')
lines.push('}')
lines.push('')
lines.push('export interface OfficialArticle {')
lines.push('  slug: string')
lines.push('  title: string')
lines.push('  description: string')
lines.push('  body: ArticleBlock[]')
lines.push('  words: number')
lines.push('}')
lines.push('')
lines.push(`export const officialArticles: OfficialArticle[] = [`)
for (const article of articles) {
  lines.push('  {')
  lines.push(`    slug: ${quote(article.slug)},`)
  lines.push(`    title: ${quote(article.title)},`)
  lines.push(`    description: ${quote(article.description)},`)
  lines.push('    body: [')
  for (const block of article.body) {
    lines.push(`      { t: ${quote(block.t)}, text: ${quote(block.text)} },`)
  }
  lines.push('    ],')
  lines.push(`    words: ${article.words},`)
  lines.push('  },')
}
lines.push(']')
lines.push('')
lines.push('const bySlug = new Map<string, OfficialArticle>()')
lines.push('for (const article of officialArticles) {')
lines.push('  bySlug.set(article.slug, article)')
lines.push('  // The crawl prefixes post files with "post__"; the app\'s blog routes do not.')
lines.push('  if (article.slug.startsWith("post__")) {')
lines.push('    bySlug.set(article.slug.slice("post__".length), article)')
lines.push('  }')
lines.push('}')
lines.push('')
lines.push('export function findOfficialArticle(slug: string) {')
lines.push('  return bySlug.get(slug) ?? bySlug.get(`post__${slug}`)')
lines.push('}')
lines.push('')

await writeFile(join(app, 'src/public/officialArticles.ts'), `${lines.join('\n')}\n`)
console.log(
  `Wrote ${articles.length} articles, ${articles.reduce((n, a) => n + a.words, 0)} words`,
)
